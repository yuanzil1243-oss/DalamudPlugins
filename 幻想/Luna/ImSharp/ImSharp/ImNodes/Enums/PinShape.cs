namespace ImSharp.ImNodes;

/// <summary> Supported shapes for pins. </summary>
public enum PinShape : uint
{
    /// <summary> A hollow circle. </summary>
    Circle,

    /// <summary> A filled circle. </summary>
    CircleFilled,

    /// <summary> A hollow, equilateral triangle. </summary>
    Triangle,

    /// <summary> A filled, equilateral triangle. </summary>
    TriangleFilled,

    /// <summary> A hollow square. </summary>
    Square,

    /// <summary> A filled square. </summary>
    SquareFilled,
}
